// Small seeded PRNG so the generated quiz is varied but identical on every run.
function mulberry32(seed: number) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const unique = <T>(values: readonly T[]) => [...new Set(values)];

function shuffle<T>(values: readonly T[], random: () => number): T[] {
  const copy = [...values];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

const artists = unique(MUSIC_FACTS.map(({ artist }) => artist));
const countries = unique(MUSIC_FACTS.map(({ country }) => country));
const genres = unique(MUSIC_FACTS.map(({ genre }) => genre));
const allTitles = unique(
  MUSIC_FACTS.flatMap(({ song, album, otherSong }) => [song, album, otherSong]),
);
const albums = unique(MUSIC_FACTS.map(({ album }) => album));

function sameGenreFamily(a: string, b: string) {
  return (
    a === b ||
    GENRE_FAMILIES.some((family) => family.includes(a) && family.includes(b))
  );
}

function wikipediaUrl({ artist, wiki }: MusicFact) {
  return wiki
    ? `https://en.wikipedia.org/wiki/${wiki}`
    : `https://en.wikipedia.org/w/index.php?search=${encodeURIComponent(`${artist} musician`)}&go=Go`;
}

function buildQuestion(
  q: string,
  correct: string,
  candidates: readonly string[],
  feedback: string,
  random: () => number,
) {
  const distractors = shuffle(
    unique(candidates).filter((value) => value !== correct),
    random,
  ).slice(0, 3);
  const c = Math.floor(random() * 4);
  const a = [...distractors];
  a.splice(c, 0, correct);
  return { q, a, c, f: feedback };
}

const generated = MUSIC_FACTS.map((fact, i) => {
  const { artist, country, song, album, genre, otherSong, year } = fact;
  const random = mulberry32(1000 + i);
  const ownTitles = new Set([song, album, otherSong]);

  // Artists who share a song title with this one are excluded so the answer stays unambiguous.
  const artistCandidates = artists.filter(
    (name) =>
      name !== artist &&
      !MUSIC_FACTS.some(
        (other) =>
          other.artist === name &&
          (other.song === song ||
            other.otherSong === song ||
            other.album === song),
      ),
  );

  // Self-titled releases make the album question trivial, so ask about the country instead.
  const albumQuestion =
    album === song
      ? buildQuestion(
          `Which country is home to the artist who recorded “${song}”?`,
          country,
          countries,
          `${artist} is from ${country}.`,
          random,
        )
      : buildQuestion(
          `Which album or EP includes “${song}” by ${artist}?`,
          album,
          albums.filter((title) => !ownTitles.has(title)),
          `“${song}” appears on ${artist}’s release ${album}.`,
          random,
        );

  const nearbyYears = [-4, -3, -2, -1, 1, 2, 3, 4].map((delta) =>
    String(year + delta),
  );

  const questions = [
    buildQuestion(
      `Which African artist recorded “${song}”?`,
      artist,
      artistCandidates,
      `“${song}” is a recording by ${artist}.`,
      random,
    ),
    albumQuestion,
    buildQuestion(
      `Which musical style is associated with ${artist}’s work?`,
      genre,
      genres.filter((candidate) => !sameGenreFamily(candidate, genre)),
      `${artist} is associated with ${genre} music.`,
      random,
    ),
    buildQuestion(
      `Which other release is in ${artist}’s discography?`,
      otherSong,
      allTitles.filter((title) => !ownTitles.has(title)),
      `“${otherSong}” is another release by ${artist}.`,
      random,
    ),
    buildQuestion(
      `In what year was ${artist}’s “${song}” released?`,
      String(year),
      nearbyYears,
      `“${song}” was released in ${year}.`,
      random,
    ),
  ];

  const source = wikipediaUrl(fact);
  return { questions, sources: questions.map(() => source) };
});

export const TRIVIA_EXTRA = generated.map(({ questions }) => questions);
export const TRIVIA_SOURCES_EXTRA = generated.map(({ sources }) => sources);
