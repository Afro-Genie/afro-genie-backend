// Direct Wikipedia titles where the default (name with underscores) would hit the wrong page.
const WIKIPEDIA_TITLE_OVERRIDES: Record<string, string> = {
  Asa: "Asa_(singer)",
  Lira: "Lira_(singer)",
  Simi: "Simi_(singer)",
  Flavour: "Flavour_N'abania",
  "Black Coffee": "Black_Coffee_(DJ)",
  Sherine: "Sherine_Abdel-Wahab",
  Khaled: "Khaled_(musician)",
  "Youssou N’Dour": "Youssou_N'Dour",
};

// Names that could not be pinned to an exact article title get a Wikipedia search link
// (go=Go jumps straight to the best-matching article) instead of a guessed URL.
const WIKIPEDIA_SEARCH_ONLY = new Set<string>(["Gigi", "Harmonize", "KiDi"]);

function wikipediaUrl(name: string): string {
  if (WIKIPEDIA_SEARCH_ONLY.has(name)) {
    return `https://en.wikipedia.org/w/index.php?search=${encodeURIComponent(`${name} musician`)}&go=Go`;
  }
  const title = WIKIPEDIA_TITLE_OVERRIDES[name] ?? name.replace(/ /g, "_");
  return `https://en.wikipedia.org/wiki/${encodeURIComponent(title)}`;
}

export const ARTIST_SOURCES_EXTRA = ARTISTS_EXTRA.map(({ name }) =>
  wikipediaUrl(name),
);
